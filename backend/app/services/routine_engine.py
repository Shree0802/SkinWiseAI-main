import uuid
from datetime import datetime, timezone
from typing import List, Optional
from app.models.schemas import RoutineRequest, RoutineResponse, RoutineStep

PATCH_TEST_GUIDELINES = (
    "How to patch-test new skincare products:\n"
    "1. Apply a pea-sized amount of the product to a clean area of your inner forearm or behind the ear.\n"
    "2. Leave the product on for 24 to 48 hours without washing the area.\n"
    "3. Check for any signs of redness, burning, itching, peeling, or swelling.\n"
    "4. If irritation occurs, wash off immediately and discontinue use. If no reaction develops, introduce the product slowly into your routine (e.g., 2-3 times per week initially)."
)

MEDICAL_DISCLAIMER = (
    "Disclaimer: SkinWise AI suggestions are intended solely for educational and cosmetic skincare purposes. "
    "They do not constitute medical diagnosis, treatment, or prescription. For persistent skin disorders, "
    "severe cystic acne, sudden rashes, or suspicious lesions, please consult a licensed medical dermatologist."
)

class RoutineEngine:
    def generate_routine(self, request: RoutineRequest) -> RoutineResponse:
        skin_type = (request.skin_type or "Combination").capitalize()
        concerns = [c.lower() for c in request.primary_concerns]
        is_minimalist = "minimalist" in [p.lower() for p in request.preferences]

        am_steps: List[RoutineStep] = []
        pm_steps: List[RoutineStep] = []

        step_counter_am = 1
        step_counter_pm = 1

        # ----------------------------------------------------
        # MORNING ROUTINE
        # ----------------------------------------------------
        # AM Step 1: Cleanser
        if skin_type in ("Oily", "Combination") or "acne" in concerns or "oiliness" in concerns:
            am_steps.append(RoutineStep(
                step_number=step_counter_am,
                phase="morning",
                step_name="Purifying Gel Cleanser",
                product_category="Cleanser",
                rationale="Gently removes overnight sebum accumulation without compromising the acid mantle.",
                recommended_ingredients=["Salicylic Acid (BHA 0.5-1%)", "Zinc PCA", "Tea Tree Leaf Water"],
                ingredients_to_avoid=["Harsh Sulfates (SLS)", "Heavy Mineral Oils"]
            ))
        elif skin_type in ("Dry", "Sensitive") or "redness" in concerns:
            am_steps.append(RoutineStep(
                step_number=step_counter_am,
                phase="morning",
                step_name="Hydrating Cream / Milk Cleanser",
                product_category="Cleanser",
                rationale="Cleanses gently while maintaining natural lipid barrier integrity and calming sensitivity.",
                recommended_ingredients=["Ceramides", "Colloidal Oatmeal", "Glycerin"],
                ingredients_to_avoid=["Drying Alcohol (Denat)", "Synthetic Fragrances"]
            ))
        else:
            am_steps.append(RoutineStep(
                step_number=step_counter_am,
                phase="morning",
                step_name="Gentle pH-Balanced Foaming Cleanser",
                product_category="Cleanser",
                rationale="Refreshes and clears surface impurities with a skin-neutral pH (5.5).",
                recommended_ingredients=["Centella Asiatica", "Green Tea", "Allantoin"],
                ingredients_to_avoid=["Strong Detergents", "Physical Micro-beads"]
            ))
        step_counter_am += 1

        # AM Step 2: Targeted Daytime Treatment (if not strictly minimalist, or targeted concern)
        if not is_minimalist or ("spots" in concerns or "wrinkles" in concerns or "texture" in concerns):
            if "spots" in concerns or "radiance" in concerns:
                am_steps.append(RoutineStep(
                    step_number=step_counter_am,
                    phase="morning",
                    step_name="Brightening Antioxidant Serum (Vitamin C / Alpha Arbutin)",
                    product_category="Serum",
                    rationale="Scavenges free radicals generated by UV exposure and lightens hyperpigmentation.",
                    recommended_ingredients=["Sodium Ascorbyl Phosphate", "Alpha Arbutin", "Ferulic Acid"],
                    ingredients_to_avoid=["Oxidized Ascorbic Acid (yellow/brown)"]
                ))
                step_counter_am += 1
            elif "pores" in concerns or "oiliness" in concerns or "acne" in concerns:
                am_steps.append(RoutineStep(
                    step_number=step_counter_am,
                    phase="morning",
                    step_name="Sebum & Pore Refining Serum (Niacinamide 5%)",
                    product_category="Serum",
                    rationale="Regulates daytime oil production and strengthens the epidermal barrier.",
                    recommended_ingredients=["Niacinamide 2-5%", "Zinc PCA", "Hyaluronic Acid"],
                    ingredients_to_avoid=["High Concentration AHA in AM"]
                ))
                step_counter_am += 1
            elif "moisture" in concerns or skin_type == "Dry":
                am_steps.append(RoutineStep(
                    step_number=step_counter_am,
                    phase="morning",
                    step_name="Multi-Weight Hyaluronic Acid Hydrating Serum",
                    product_category="Serum",
                    rationale="Draws water into deeper epidermis layers to sustain all-day skin plumpness.",
                    recommended_ingredients=["Sodium Hyaluronate", "Panthenol (B5)", "Beta-Glucan"],
                    ingredients_to_avoid=["Drying Astringents"]
                ))
                step_counter_am += 1

        # AM Step 3: Daytime Moisturizer
        if skin_type in ("Oily", "Combination") and "oiliness" in concerns:
            am_steps.append(RoutineStep(
                step_number=step_counter_am,
                phase="morning",
                step_name="Oil-Free Matte Hydration Gel",
                product_category="Moisturizer",
                rationale="Provides lightweight, non-comedogenic moisture that leaves a shine-free finish.",
                recommended_ingredients=["Glycerin", "Centella Asiatica", "Squalane (Olive-derived)"],
                ingredients_to_avoid=["Heavy Shea Butter", "Comedogenic Waxes"]
            ))
        else:
            am_steps.append(RoutineStep(
                step_number=step_counter_am,
                phase="morning",
                step_name="Barrier Restorative Day Lotion",
                product_category="Moisturizer",
                rationale="Locks in moisture with lightweight lipids to protect against environmental stressors.",
                recommended_ingredients=["Ceramide NP", "Peptides", "Panthenol"],
                ingredients_to_avoid=["Heavy Petrolatum before sunscreen"]
            ))
        step_counter_am += 1

        # AM Step 4: Broad-Spectrum Sunscreen (Non-negotiable)
        am_steps.append(RoutineStep(
            step_number=step_counter_am,
            phase="morning",
            step_name="Broad-Spectrum Daily Sunscreen SPF 50+ PA++++",
            product_category="Sunscreen",
            rationale="Essential daily photoprotection against UVA/UVB rays preventing premature aging and dark spot darkening.",
            recommended_ingredients=["Modern UV Filters (Tinosorb, Uvinul)", "Zinc Oxide", "Ectoin"],
            ingredients_to_avoid=["Expired Filters", "Unstable Oxybenzone (if sensitive)"]
        ))

        # ----------------------------------------------------
        # EVENING ROUTINE
        # ----------------------------------------------------
        # PM Step 1: Cleansing
        if skin_type in ("Oily", "Combination") or not is_minimalist:
            pm_steps.append(RoutineStep(
                step_number=step_counter_pm,
                phase="evening",
                step_name="Micellar Water or Gentle Oil Cleanser (Double Cleanse)",
                product_category="Cleanser",
                rationale="Thoroughly dissolves sunscreen, air pollution particulates, and accumulated sebum.",
                recommended_ingredients=["Jojoba Oil", "Caprylic/Capric Triglyceride", "Poloxamer 184"],
                ingredients_to_avoid=["Comedogenic Mineral Waxes"]
            ))
            step_counter_pm += 1

        pm_steps.append(RoutineStep(
            step_number=step_counter_pm,
            phase="evening",
            step_name="Balancing Water-Based Evening Wash",
            product_category="Cleanser",
            rationale="Rinses away residue and prepares the epidermal layer for nighttime active absorption.",
            recommended_ingredients=["Glycerin", "Allantoin", "Amino Acid Surfactants"],
            ingredients_to_avoid=["High-pH Bar Soaps"]
        ))
        step_counter_pm += 1

        # PM Step 2: Night Active Treatment
        if "wrinkles" in concerns or "firmness" in concerns or "texture" in concerns:
            pm_steps.append(RoutineStep(
                step_number=step_counter_pm,
                phase="evening",
                step_name="Gentle Night Renewal Serum (Encapsulated Retinal / Granactive Retinoid)",
                product_category="Treatment",
                rationale="Promotes cellular turnover and collagen synthesis overnight; start 2 nights per week.",
                recommended_ingredients=["Granactive Retinoid 2%", "Bakuchiol", "Ceramides"],
                ingredients_to_avoid=["Concurrently layering strong AHA peels"]
            ))
            step_counter_pm += 1
        elif "acne" in concerns or "pores" in concerns:
            pm_steps.append(RoutineStep(
                step_number=step_counter_pm,
                phase="evening",
                step_name="Clarifying BHA / Azelaic Acid Night Exfoliant",
                product_category="Treatment",
                rationale="Clears clogged follicular ducts, mitigates inflammation, and prevents nighttime congestion.",
                recommended_ingredients=["Azelaic Acid 10%", "Salicylic Acid 2%", "Green Tea Extract"],
                ingredients_to_avoid=["Physical Abrasive Scrubs"]
            ))
            step_counter_pm += 1
        elif "spots" in concerns:
            pm_steps.append(RoutineStep(
                step_number=step_counter_pm,
                phase="evening",
                step_name="Tone-Correcting Tranexamic & Niacinamide Elixir",
                product_category="Treatment",
                rationale="Inhibits melanin transfer and fades persistent post-inflammatory marks.",
                recommended_ingredients=["Tranexamic Acid 3-5%", "Niacinamide", "Licorice Root Extract"],
                ingredients_to_avoid=["Harsh hydroquinone without physician supervision"]
            ))
            step_counter_pm += 1
        else:
            pm_steps.append(RoutineStep(
                step_number=step_counter_pm,
                phase="evening",
                step_name="Barrier Recovery & Soothing Peptide Complex",
                product_category="Treatment",
                rationale="Nourishes skin matrix, reinforces skin resilience, and reduces daily stress signs.",
                recommended_ingredients=["Copper Tripeptides", "Centella Asiatica (Cica)", "Ectoin"],
                ingredients_to_avoid=["Excessive actives simultaneously"]
            ))
            step_counter_pm += 1

        # PM Step 3: Night Recovery Cream
        pm_steps.append(RoutineStep(
            step_number=step_counter_pm,
            phase="evening",
            step_name="Night Barrier Repair Cream",
            product_category="Moisturizer",
            rationale="Replenishes essential ceramides and fatty acids while you sleep to prevent transepidermal water loss (TEWL).",
            recommended_ingredients=["Ceramide NP/AP/EOP", "Cholesterol", "Phytosphingosine", "Squalane"],
            ingredients_to_avoid=["Irritating Essential Oils"]
        ))

        return RoutineResponse(
            routine_id=str(uuid.uuid4()),
            created_at=datetime.now(timezone.utc).isoformat(),
            target_skin_type=skin_type,
            target_concerns=request.primary_concerns,
            morning_steps=am_steps,
            evening_steps=pm_steps,
            patch_test_guidelines=PATCH_TEST_GUIDELINES,
            medical_disclaimer=MEDICAL_DISCLAIMER
        )

routine_engine = RoutineEngine()
